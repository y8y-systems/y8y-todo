#!/usr/bin/env python3
"""中国法定节假日年度更新器（stdlib-only）。

设计要点（改这个文件前先读 docs/cn-holiday-updater.md）：

* 唯一数据真源是 ``holidays/cn-holidays.json``；``src/index.html`` 里只有一段
  由本脚本生成的 **受保护区块**（BEGIN/END marker 之间）。运行时仍是内联常量，
  不发网络请求、不需要构建步骤、离线可用。
* 每年 11/16、12/16、1/16 检查一次。1 月查当年，其余月份查下一年。
* 官方通知的「是否发布」有两层独立官方来源：首选中国政府网「最新政策」
  结构化索引；找不到时必须再查**国务院政策文件库的历史归档检索**（覆盖
  2007 年至今全部节假日通知），避免通知退出最新列表后被误判为「未公布」。
  历史归档自身还要用「是否含往年通知」自检；只有两个官方来源都确认缺失，
  才能报 not-published。任何一步无法确认 → check-unavailable，绝不误报。
* 通知全文只从可信域名取，且必须**逐条严格解析 + 交叉校验**通过才写入。
  任何不确定 → 报告并转人工，绝不猜测日期、绝不写占位数据。
* 写入是原子的：先在内存里生成两个文件的完整内容，再用临时文件 + rename
  替换；任何一步失败都回滚到写入前的字节，不留下半写入文件。
* 幂等：目标年份已有完整安排 → 一个字节都不改。

命令::

    python3 scripts/cn_holiday_updater.py check   --today 2026-11-16
    python3 scripts/cn_holiday_updater.py apply   --today 2026-11-16
    python3 scripts/cn_holiday_updater.py regenerate
    python3 scripts/cn_holiday_updater.py verify

离线/CI 用 ``--index-feed`` / ``--history-feed`` / ``--exact-feed`` /
``--notice-html`` 喂固定样本；不加这些参数且允许联网时才访问中国政府网。
"""
