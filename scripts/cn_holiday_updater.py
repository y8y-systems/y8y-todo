def target_year(today: dt.date) -> int:
    """1 月查当年（防漏录），其余月份查下一年。年份绝不硬编码。"""
    return today.year if today.month == 1 else today.year + 1


def next_check(today: dt.date) -> str:
    """下一次固定检查（11/16、12/16、1/16，日本时间 10:00）。"""
    candidates = [
        dt.date(today.year, 11, 16),
        dt.date(today.year, 12, 16),
        dt.date(today.year + 1, 1, 16),
    ]
    for d in candidates:
        if d > today:
            return "%s 10:00 JST" % d.isoformat()
    return "%s 10:00 JST" % dt.date(today.year + 1, 11, 16).isoformat()


def today_jst() -> dt.date:
    # 日本标准时间固定 UTC+9，无夏令时；不依赖 tzdata。
    return dt.datetime.now(dt.timezone(dt.timedelta(hours=9))).date()


# ── 结构化数据 ─────────────────────────────────────────────────────────────

def load_data(path=None) -> dict:
    # 不能用默认参数绑定 DATA_PATH：默认参数在函数定义时求值，--root 覆盖后会读错文件。
    path = Path(path) if path is not None else DATA_PATH
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise UpdaterError("节假日数据文件读取失败: %s" % exc) from exc
    if not isinstance(data, dict) or data.get("schema") != 1:
        raise UpdaterError("节假日数据文件 schema 不为 1")
    for key in ("fixed_festivals", "sources", "festivals", "schedules"):
        if key not in data:
            raise UpdaterError("节假日数据文件缺少 %s" % key)
    return data


def _js_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _ranges_lines(ranges: list, indent: str = "      ") -> list:
    """两行一组，保持与原有 index.html 相近的排版。"""
    lines = []
    for i in range(0, len(ranges), 2):
        chunk = ranges[i:i + 2]
        body = ", ".join(
            "[%s, %s, %s]" % (_js_str(a), _js_str(b), _js_str(c))
            for a, b, c in chunk
        )
        lines.append("%s%s," % (indent, body))
    return lines


def render_block(data: dict) -> str:
    """从结构化数据生成 index.html 里唯一允许被改写的 JS 区块。"""
    sources = data["sources"]
    src_note = "; ".join(
        "%s = %s" % (year, info.get("wenhao") or "（无文号）")
        for year, info in sorted(sources.items())
    )
    lines = [
        BEGIN_MARKER,
        "// ── 中国法定节假日 (与日本祝日同款显示在日期右侧; 可按部署配置开关) ──",
        "// 中国的放假安排由国务院逐年公布(含调休连休), 不像日本能靠规则推算 → 逐年录入官方通知原文;",
        "// 未收录的年份只标「节日本身」(固定公历日 + 农历节日对应的公历日)。",
        "// 本区块由 holidays/cn-holidays.json 生成 (scripts/cn_holiday_updater.py), 请勿手改。",
        "// 来源: %s。" % (src_note or "（暂无）"),
        "const CN_HOLIDAY_SCHEDULE = {",
    ]
    for year in sorted(data["schedules"]):
        sch = data["schedules"][year]
        lines.append("  %s: {" % _js_str(year))
        lines.append("    ranges: [")
        lines.extend(_ranges_lines(sch["ranges"]))
        lines.append("    ],")
        overrides = sch.get("overrides") or {}
        if overrides:
            ov = ", ".join("%s: %s" % (_js_str(k), _js_str(v))
                           for k, v in sorted(overrides.items()))
            lines.append("    overrides: { %s }," % ov)
        else:
            lines.append("    overrides: {},")
        lines.append("    workdays: [%s]," % ", ".join(_js_str(w) for w in sch["workdays"]))
        lines.append("  },")
    lines.append("};")
    lines.append("// 节日本身 (国务院还没公布安排 / 早年年份用): 固定公历日 + 农历节日的公历日")
    lines.append("const CN_FESTIVALS = {")
    for year in sorted(data["festivals"]):
        pairs = ", ".join("[%s, %s]" % (_js_str(a), _js_str(b))
                          for a, b in data["festivals"][year])
        lines.append("  %s: [%s]," % (_js_str(year), pairs))
    lines.append("};")
    fixed = ", ".join("[%s, %s]" % (_js_str(a), _js_str(b))
                      for a, b in data["fixed_festivals"])
    lines.append("const CN_FIXED_FESTIVALS = [%s];" % fixed)
    lines.append(END_MARKER)
    return "\n".join(lines) + "\n"


def split_index(text: str):
    """把 index.html 切成 (前缀, 受保护区块, 后缀)。marker 必须各出现一次。"""
    if text.count(BEGIN_MARKER) != 1 or text.count(END_MARKER) != 1:
        raise UpdaterError("index.html 的节假日受保护区块 marker 缺失或重复")
    start = text.index(BEGIN_MARKER)
    end = text.index(END_MARKER)
    if end < start:
        raise UpdaterError("index.html 的节假日 marker 顺序错误")
    line_end = text.find("\n", end)
    if line_end == -1:
        line_end = len(text)
    else:
        line_end += 1
    return text[:start], text[start:line_end], text[line_end:]


def media_count(text: str) -> int:
    return len([ln for ln in text.splitlines() if ln.startswith("@media")])


def replace_block(text: str, new_block: str) -> str:
    """只替换受保护区块；前缀/后缀逐字节不变，@media 头数量不变。"""
    prefix, old_block, suffix = split_index(text)
    if "@media" in new_block:
        raise UpdaterError("生成的节假日区块里出现 @media —— 拒绝写入")
    out = prefix + new_block + suffix
    if media_count(out) != media_count(text):
        raise UpdaterError("写入后 @media 头数量变化 —— 拒绝写入")
    if out[:len(prefix)] != prefix or not out.endswith(suffix):
        raise UpdaterError("写入会改动受保护区块之外的代码 —— 拒绝写入")
    if out == text:
        raise UpdaterError("受保护区块没有变化")
    return out


# ── 校验 ───────────────────────────────────────────────────────────────────

def _parse_mmdd(mmdd: str, year: int):
    m = re.fullmatch(r"(\d{2})-(\d{2})", mmdd or "")
    if not m:
        return None
    try:
        return dt.date(year, int(m.group(1)), int(m.group(2)))
    except ValueError:
        return None


def validate_schedule(year: int, schedule: dict, data: dict) -> list:
    """返回错误列表（空 = 通过）。任何错误都不允许写入数据。"""
    errors = []
    if not isinstance(schedule, dict):
        return ["schedule 不是对象"]
    ranges = schedule.get("ranges")
    overrides = schedule.get("overrides") or {}
    workdays = schedule.get("workdays")

    if not isinstance(ranges, list) or not ranges:
        return ["缺少放假区间 ranges"]
    if not isinstance(workdays, list) or not workdays:
        errors.append("缺少调休上班日 workdays（通知未确认，禁止写入）")

    seen_ranges = []
    covered_names = set()
    for item in ranges:
        if not (isinstance(item, list) and len(item) == 3):
            errors.append("放假区间格式错误: %r" % (item,))
            continue
        a, b, name = item
        if name not in SEVEN_FESTIVALS:
            errors.append("未知节日名称: %r" % (name,))
        start, end = _parse_mmdd(a, year), _parse_mmdd(b, year)
        if start is None or end is None:
            errors.append("无效日期: %r -> %r" % (a, b))
            continue
        if start > end:
            # MM-DD 结构无法表达跨年区间；静默回绕会写错整年数据。
            errors.append("跨年/倒序区间 %s -> %s：当前数据结构不支持，需人工确认" % (a, b))
            continue
        covered_names.add(name)
        for prev in seen_ranges:
            if start <= prev[1] and prev[0] <= end:
                errors.append("节日区间重叠: %s~%s 与 %s~%s" %
                              (a, b, prev[0].isoformat(), prev[1].isoformat()))
        seen_ranges.append((start, end, a, b))

    if isinstance(overrides, dict):
        for mmdd, name in overrides.items():
            d = _parse_mmdd(mmdd, year)
            if d is None:
                errors.append("覆盖标签日期无效: %r" % (mmdd,))
            elif not any(s <= d <= e for s, e, _, _ in seen_ranges):
                errors.append("覆盖标签 %s 不在任何放假区间内" % mmdd)
            if name not in SEVEN_FESTIVALS:
                errors.append("覆盖标签节日名无效: %r" % (name,))
            covered_names.add(name)
    else:
        errors.append("overrides 不是对象")

    if isinstance(workdays, list):
        if len(workdays) != len(set(workdays)):
            errors.append("调休上班日有重复日期")
        seen_days = set()
        for mmdd in workdays:
            d = _parse_mmdd(mmdd, year)
            if d is None:
                errors.append("调休上班日无效: %r" % (mmdd,))
                continue
            if mmdd in seen_days:
                errors.append("调休上班日重复: %s" % mmdd)
            seen_days.add(mmdd)
            if any(s <= d <= e for s, e, _, _ in seen_ranges):
                errors.append("调休上班日 %s 落在放假区间内" % mmdd)
    else:
        errors.append("workdays 不是数组")

    missing = set(SEVEN_FESTIVALS) - covered_names
    if missing:
        errors.append("七个主要节日未覆盖: %s" % "、".join(sorted(missing)))

    festivals = data.get("festivals", {}).get(str(year))
    if festivals is not None:
        names = [name for _, name in festivals]
        if len(names) != len(set(names)):
            errors.append("节日本身日期有重复节日名")
        for mmdd, name in festivals:
            d = _parse_mmdd(mmdd, year)
            if d is None:
                errors.append("节日本身日期无效: %r" % (mmdd,))
            elif not any(s <= d <= e for s, e, _, _ in seen_ranges):
                errors.append("节日本身 %s(%s) 不在任何放假区间内" % (name, mmdd))
    return errors


def validate_data(data: dict) -> list:
    errors = []
    for year, schedule in sorted(data.get("schedules", {}).items()):
        if not re.fullmatch(r"\d{4}", str(year)):
            errors.append("非法年份键: %r" % (year,))
            continue
        for msg in validate_schedule(int(year), schedule, data):
            errors.append("%s: %s" % (year, msg))
    return errors


# ── 官方通知：发现 / 抓取 / 解析 ────────────────────────────────────────────

def expected_title(year: int) -> str:
    return "国务院办公厅关于%d年部分节假日安排的通知" % year


def discover(feed_bytes, year: int):
    """从中国政府网结构化索引里找目标年份的**正式通知原文**。

    返回 (entries, error_code)。error_code: None / 'check-unavailable' /
    'source-conflict' / 'untrusted-source'。
    """
    try:
        feed = json.loads(feed_bytes.decode("utf-8") if isinstance(feed_bytes, bytes)
                          else str(feed_bytes))
    except (ValueError, UnicodeDecodeError, AttributeError) as exc:
        return [], "check-unavailable: 政策索引不是合法 JSON (%s)" % exc
    if not isinstance(feed, list):
        return [], "check-unavailable: 政策索引结构不是数组"

    wanted = expected_title(year)
    hits = []
    for entry in feed:
        if not isinstance(entry, dict):
            continue
        title = re.sub(r"\s+", "", str(entry.get("TITLE") or ""))
        if title == wanted:
            hits.append(entry)
    if not hits:
        return [], None  # 尚未发布 —— 正常、可预期的状态

    urls = []
    for entry in hits:
        url = str(entry.get("URL") or "")
        if url not in urls:
            urls.append(url)
    if len(urls) > 1:
        return [], "source-conflict: 政策索引里出现 %d 个不同的官方通知地址，停止自动提交" % len(urls)
    url = urls[0]
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.hostname not in TRUSTED_HOSTS:
        return [], "untrusted-source: 通知地址不是可信官方域名"
    return [hits[0]], None


# ── 官方历史归档兜底 ───────────────────────────────────────────────────────
#
# 「最新政策」索引是滚动列表，通知可能退出列表；只靠它判定「未公布」会漏检。
# 国务院政策文件库检索是独立的官方历史归档，按标题可一次取回 2007 年至今
# 全部《…部分节假日安排的通知》。它同时自带可用性自检：如果连往年通知都
# 查不到，说明检索本身不可信 → 必须返回 check-unavailable，绝不误报。

def _normal_title(value) -> str:
    """检索结果标题带 <em> 高亮标签与空白，比较前先归一化。"""
    return re.sub(r"\s+", "", html_lib.unescape(
        re.sub(r"<[^>]+>", "", str(value or ""))))


def _history_date(value) -> str:
    m = re.search(r"(\d{4})[.\-/](\d{1,2})[.\-/](\d{1,2})", str(value or ""))
    if not m:
        return ""
    return "%04d-%02d-%02d" % (int(m.group(1)), int(m.group(2)), int(m.group(3)))


def _history_payload(raw):
    try:
        payload = json.loads(raw.decode("utf-8") if isinstance(raw, bytes) else str(raw))
    except (ValueError, UnicodeDecodeError, AttributeError) as exc:
        return None, "check-unavailable: 历史政策检索结果不是合法 JSON (%s)" % exc
    if not isinstance(payload, dict):
        return None, "check-unavailable: 历史政策检索结构不是对象"
    return payload, None


def _history_by_year(payload):
    """返回 (by_year, problem)。by_year: {年份: [统一条目]}。"""
    sv = payload.get("searchVO")
    if not isinstance(sv, dict) or not isinstance(sv.get("listVO"), list):
        return {}, "check-unavailable: 历史政策检索缺少结果列表"
    by_year = {}
    for item in sv["listVO"]:
        if not isinstance(item, dict):
            continue
        m = ARCHIVE_TITLE_RE.fullmatch(_normal_title(item.get("title")))
        if not m:
            continue
        year = int(m.group(1))
        url = str(item.get("url") or "")
        parts = urllib.parse.urlsplit(url)
        if parts.scheme != "https" or parts.hostname not in TRUSTED_HOSTS:
            return {}, "untrusted-source: 历史政策检索里的通知地址不是可信官方域名"
        by_year.setdefault(year, []).append({
            "TITLE": expected_title(year),
            "URL": url,
            "DOCRELPUBTIME": _history_date(item.get("pubtimeStr")),
            "PCODE": str(item.get("pcode") or ""),
        })
    return by_year, None


def _single_year_entry(by_year, year):
    """目标年份多个不同官方地址 → 冲突；否则返回 (entry, status, reason)。"""
    hits = by_year.get(year, [])
    urls = []
    for e in hits:
        if e["URL"] not in urls:
            urls.append(e["URL"])
    if len(urls) > 1:
        return None, "source-conflict", "历史政策库出现 %d 个不同的目标年份通知地址，停止自动提交" % len(urls)
    if urls:
        return hits[0], "found", ""
    return None, "absent", ""


def discover_history_archive(raw, year: int):
    """解析历史归档检索结果。返回 (entry, status, reason)。

    status: found / absent / check-unavailable / untrusted-source / source-conflict
    """
    payload, problem = _history_payload(raw)
    if problem:
        code, _, msg = problem.partition(": ")
        return None, code, msg
    if payload.get("code") != 200:
        return None, "check-unavailable", (
            "历史政策库返回 code=%r，无法确认是否已发布" % payload.get("code"))
    by_year, problem = _history_by_year(payload)
    if problem:
        code, _, msg = problem.partition(": ")
        return None, code, msg
    # 自检：归档里必须能查到往年通知，否则这个「历史库」本身不可信。
    prior = [y for y in by_year if y < year]
    if not prior:
        return None, "check-unavailable", (
            "历史政策库未返回任何往年节假日通知，无法确认索引是否可用")
    return _single_year_entry(by_year, year)


def confirm_exact_year(raw, year: int):
    """精确年份检索的二次确认。返回 (entry, status, reason)。"""
    payload, problem = _history_payload(raw)
    if problem:
        code, _, msg = problem.partition(": ")
        return None, code, msg
    code = payload.get("code")
    if code == NO_RESULT_CODE:
        # 官方接口对「没有找到相关结果」有明确返回码，可作为正向的缺席证据。
        return None, "absent", ""
    if code != 200:
        return None, "check-unavailable", (
            "精确年份检索返回 code=%r，无法确认是否已发布" % code)
    by_year, problem = _history_by_year(payload)
    if problem:
        c, _, msg = problem.partition(": ")
        return None, c, msg
    return _single_year_entry(by_year, year)


def confirm_via_history(year: int, history_bytes=None, exact_bytes=None,
                        allow_network=True):
    """最新政策索引没找到时，用官方历史归档确认。返回 (entry, status, reason)。"""
    if history_bytes is None:
        if not allow_network:
            return None, "check-unavailable", "缺少历史政策检索离线样本且禁止联网"
        try:
            history_bytes = fetch(search_url(ARCHIVE_QUERY), hosts=INDEX_HOSTS)
        except FetchError as exc:
            return None, "check-unavailable", "历史政策库不可达，无法确认：%s" % exc
    entry, status, reason = discover_history_archive(history_bytes, year)
    if status != "absent":
        return entry, status, reason

    # 归档健康但缺目标年份 → 再查一次精确年份，双重确认「确实没发布」。
    if exact_bytes is None:
        if not allow_network:
            return None, "check-unavailable", "缺少精确年份检索离线样本且禁止联网"
        try:
            exact_bytes = fetch(search_url(expected_title(year), page_size=10),
                                hosts=INDEX_HOSTS)
        except FetchError as exc:
            return None, "check-unavailable", "精确年份检索不可达，无法确认：%s" % exc
    entry2, status2, reason2 = confirm_exact_year(exact_bytes, year)
    if status2 == "found":
        return entry2, "found", "（由精确年份检索补齐，尚未进入历史归档列表）"
    if status2 == "absent":
        return None, "not-published", ""
    return None, status2, reason2


def search_url(query: str, page_size: int = 50) -> str:
    """国务院政策文件库检索地址（只由本模块构造，不接受外部输入）。"""
    params = {
        "t": "zhengcelibrary_gw", "q": query, "p": 1, "n": page_size,
        "sort": "score", "sortType": 1, "searchfield": "title",
    }
    return SEARCH_ENDPOINT + "?" + urllib.parse.urlencode(params)


def fetch(url: str, timeout: int = 15, hosts=None) -> bytes:
    # 默认只放行通知全文域名；检索接口需要显式传 hosts=INDEX_HOSTS。
    allowed = TRUSTED_HOSTS if hosts is None else hosts
    parts = urllib.parse.urlsplit(url)
    if parts.scheme != "https" or parts.hostname not in allowed:
        raise FetchError("不可信的官方来源，拒绝抓取")
    req = urllib.request.Request(
        url, headers={"User-Agent": "y8y-todo-cn-holiday-updater/1.0"}
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.read(2_000_000)
    except Exception as exc:  # urllib 的异常类型很多，统一转成可报告错误
        raise FetchError("抓取官方页面失败 (%s)" % type(exc).__name__) from exc


def html_to_text(raw) -> str:
    s = raw.decode("utf-8", "replace") if isinstance(raw, bytes) else str(raw)
    s = re.sub(r"(?is)<(script|style).*?</\1>", "", s)
    s = html_lib.unescape(re.sub(r"(?s)<[^>]+>", "", s))
    return re.sub(r"\s+", "", s)


_FESTIVAL_ALT = "|".join(SEVEN_FESTIVALS)
# 条款头必须出现在句首（紧跟句号或正文开头），且只由七个法定节日名组成。
# 「农历正月初七、周一)」里的「七、」曾被引擎误当成条款头，这条约束专门防它。
CLAUSE_RE = re.compile(
    r"(?:(?<=^)|(?<=。))([一二三四五六七])、"
    r"((?:" + _FESTIVAL_ALT + r")(?:、(?:" + _FESTIVAL_ALT + r"))*)："
)
RANGE_RE = re.compile(
    r"(?P<m1>\d{1,2})月(?P<d1>\d{1,2})日(?P<p1>（[^）]*）)?"
    r"(?:至(?:(?P<m2>\d{1,2})月)?(?P<d2>\d{1,2})日(?P<p2>（[^）]*）)?)?"
    r"放假(?:调休)?"
    r"(?:，共(?P<n1>\d+)天|(?P<n2>\d+)天)"
    r"(?:，不调休)?。"
)
WORK_SENTENCE_RE = re.compile(r"(?P<body>[^。]*?)上班。")
WORK_TOKEN_RE = re.compile(r"(\d{1,2})月(\d{1,2})日（周([一二三四五六日天])）")
WENHAO_RE = re.compile(r"国办发(?:明电)?〔(?P<y>\d{4})〕(?P<n>\d+)号")


def _weekday_ok(paren: str, d: dt.date) -> bool:
    m = re.search(r"周([一二三四五六日天])", paren or "")
    if not m:
        return True  # 没写星期就不校验
    return WEEKDAY_CHAR[m.group(1)] == d.weekday()


def _date(year: int, month: str, day: str):
    try:
        return dt.date(year, int(month), int(day))
    except ValueError:
        return None


def parse_notice(raw, year: int, data: dict, url: str = "", published: str = ""):
    """严格解析国务院办公厅通知全文。返回 (candidate, errors)。"""
    errors = []
    text = html_to_text(raw)
    title = expected_title(year)
    if title not in text:
        errors.append("页面不含目标年份的正式通知标题 %s" % title)
        return None, errors

    wenhao_m = WENHAO_RE.search(text)
    wenhao = wenhao_m.group(0) if wenhao_m else None

    # 只解析「具体安排通知如下」到正文结束之间的七条（或六条，合并节日时）。
    anchor = text.find("具体安排通知如下")
    segment = text[anchor + len("具体安排通知如下"):] if anchor >= 0 else text
    cut_positions = [segment.find(k) for k in ("鼓励单位", "节假日期间", "国务院办公厅%d年" % (year - 1))]
    cut_positions = [p for p in cut_positions if p >= 0]
    if cut_positions:
        segment = segment[:min(cut_positions)]

    clauses = list(CLAUSE_RE.finditer(segment))
    if not clauses:
        errors.append("通知正文里找不到逐条节假日安排")
        return None, errors
    expected_ordinals = [ORDINALS[i] for i in range(len(clauses))]
    if [m.group(1) for m in clauses] != expected_ordinals:
        errors.append("通知条款序号不连续或缺失")
        return None, errors

    all_names = []
    parsed_ranges = []
    workdays = []
    combined_extra_names = []

    for idx, m in enumerate(clauses):
        names = [n.strip() for n in m.group(2).split("、") if n.strip()]
        if not names or any(n not in SEVEN_FESTIVALS for n in names):
            errors.append("第%s条节日名称无法识别: %s" % (m.group(1), m.group(2)))
            continue
        all_names.extend(names)
        body_start = m.end()
        body_end = clauses[idx + 1].start() if idx + 1 < len(clauses) else len(segment)
        body = segment[body_start:body_end]

        rm = RANGE_RE.match(body)
        if not rm:
            errors.append("第%s条放假区间无法严格解析（转入人工确认）" % m.group(1))
            continue
        d1 = _date(year, rm.group("m1"), rm.group("d1"))
        if d1 is None:
            errors.append("第%s条起始日期无效" % m.group(1))
            continue
        if rm.group("d2"):
            m2 = rm.group("m2") or rm.group("m1")
            d2 = _date(year, m2, rm.group("d2"))
        else:
            d2 = d1
        if d2 is None:
            errors.append("第%s条结束日期无效" % m.group(1))
            continue
        if d2 < d1:
            errors.append("第%s条为跨年/倒序区间，MM-DD 数据结构不支持" % m.group(1))
            continue
        declared = int(rm.group("n1") or rm.group("n2"))
        actual = (d2 - d1).days + 1
        if declared != actual:
            errors.append("第%s条「共%d天」与区间实际 %d 天不一致" %
                          (m.group(1), declared, actual))
            continue
        if not _weekday_ok(rm.group("p1") or "", d1) or not _weekday_ok(rm.group("p2") or "", d2):
            errors.append("第%s条区间端点星期与通知不符" % m.group(1))
            continue
        parsed_ranges.append([d1.strftime("%m-%d"), d2.strftime("%m-%d"), names[0]])
        if len(names) > 1:
            combined_extra_names.extend(names[1:])

        rest = body[rm.end():]
        wm = WORK_SENTENCE_RE.match(rest)
        if wm:
            token_body = wm.group("body")
            tokens = WORK_TOKEN_RE.findall(token_body)
            rebuilt = "、".join("%s月%s日（周%s）" % t for t in tokens)
            if not tokens or rebuilt != token_body:
                errors.append("第%s条调休上班日格式无法严格解析" % m.group(1))
                continue
            for mm, dd, wd in tokens:
                wd_date = _date(year, mm, dd)
                if wd_date is None:
                    errors.append("第%s条调休上班日无效: %s月%s日" % (m.group(1), mm, dd))
                    continue
                if WEEKDAY_CHAR[wd] != wd_date.weekday():
                    errors.append("第%s条 %s月%s日 的星期与通知不符" % (m.group(1), mm, dd))
                    continue
                workdays.append(wd_date.strftime("%m-%d"))
            tail = rest[wm.end():]
            if re.search(r"\d{1,2}月\d{1,2}日[^。]{0,30}上班|共\d+天", tail):
                errors.append("第%s条正文尾部还有未解析的放假/上班日期" % m.group(1))
        elif re.search(r"\d{1,2}月\d{1,2}日[^。]{0,30}上班", rest):
            errors.append("第%s条存在无法严格解析的上班日" % m.group(1))

    if sorted(set(all_names)) != sorted(SEVEN_FESTIVALS):
        errors.append("通知未覆盖七个主要节日: 缺 %s" %
                      "、".join(sorted(set(SEVEN_FESTIVALS) - set(all_names))))
    if len(workdays) != len(set(workdays)):
        errors.append("调休上班日出现重复日期")
    if not workdays:
        errors.append("通知未列出任何调休上班日（需人工确认是否确实没有调休）")

    festivals = data.get("festivals", {}).get(str(year))
    if not festivals or len(festivals) != len(SEVEN_FESTIVALS):
        errors.append("缺少 %d 年「节日本身」日期（农历节日需人工补录），无法生成覆盖标签" % year)
        return None, errors

    range_objs = []
    for a, b, name in parsed_ranges:
        s, e = _parse_mmdd(a, year), _parse_mmdd(b, year)
        if s and e:
            range_objs.append((s, e, name))
    overrides = {}
    for mmdd, name in festivals:
        d = _parse_mmdd(mmdd, year)
        if d is None:
            errors.append("节日本身日期无效: %s" % mmdd)
            continue
        containing = [r for r in range_objs if r[0] <= d <= r[1]]
        if not containing:
            errors.append("节日本身 %s(%s) 不在任何放假区间内" % (name, mmdd))
        elif containing[0][2] != name:
            overrides[mmdd] = name

    parsed_ranges.sort(key=lambda r: r[0])
    schedule = {
        "ranges": parsed_ranges,
        "overrides": dict(sorted(overrides.items())),
        "workdays": sorted(set(workdays)),
    }
    if errors:
        return None, errors
    errors.extend(validate_schedule(year, schedule, data))
    if errors:
        return None, errors

    candidate = {
        "year": year,
        "title": title,
        "wenhao": wenhao,
        "url": url,
        "published": published,
        "schedule": schedule,
    }
    return candidate, []


