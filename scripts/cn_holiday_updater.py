def _status(code, year, message, **extra):
    out = {"status": code, "target_year": year, "message": message}
    out.update(extra)
    return out


def run_check(data: dict, today: dt.date, feed_bytes=None, notice_bytes=None,
              notice_url=None, allow_network=True, history_bytes=None,
              exact_bytes=None) -> dict:
    year = target_year(today)
    base = {"next_check": next_check(today)}
    if str(year) in data["schedules"]:
        return _status("already-present", year,
                       "%d 年完整放假安排已存在，不修改任何文件。" % year, **base)

    # 首选来源：最新政策索引。抓取/解析失败也交给历史归档兜底，
    # 但「首选不可用」时不允许把历史归档的缺席当成完整确认。
    primary_reason = ""
    if feed_bytes is not None:
        entries, problem = discover(feed_bytes, year)
    elif not allow_network:
        entries, problem = [], "check-unavailable: 未提供政策索引离线样本且禁止联网"
    else:
        try:
            entries, problem = discover(fetch(FEED_URL), year)
        except FetchError as exc:
            entries, problem = [], "check-unavailable: 官方政策索引不可达 (%s)" % exc

    if problem:
        code = problem.split(":", 1)[0]
        if code in ("untrusted-source", "source-conflict"):
            return _status(code, year, problem.split(":", 1)[1].strip(), **base)
        primary_reason = problem.split(":", 1)[1].strip()
        entries = []

    source_note = "最新政策索引"
    if not entries:
        # 关键修复：滚动列表里没有 ≠ 官方没发布。必须用独立的官方历史归档确认，
        # 且历史归档自身要能查到往年通知；任何一步无法确认都不许报 not-published。
        hist_entry, hist_status, hist_reason = confirm_via_history(
            year, history_bytes=history_bytes, exact_bytes=exact_bytes,
            allow_network=allow_network)
        if hist_status == "check-unavailable":
            extra = "（首选来源同样不可用：%s）" % primary_reason if primary_reason else ""
            return _status(
                "check-unavailable", year,
                "最新政策索引未见 %d 年通知，且官方历史归档无法确认是否已发布：%s%s；"
                "不误报「未公布」。下次自动检查 %s。"
                % (year, hist_reason, extra, next_check(today)), **base)
        if hist_status in ("untrusted-source", "source-conflict"):
            return _status(hist_status, year, hist_reason, **base)
        if hist_status == "not-published":
            if primary_reason:
                return _status(
                    "check-unavailable", year,
                    "首选政策索引不可用（%s），虽历史归档未见 %d 年通知，仍无法完整确认；"
                    "不误报「未公布」。下次自动检查 %s。"
                    % (primary_reason, year, next_check(today)), **base)
            return _status(
                "not-published", year,
                "%d 年安排经「最新政策索引 + 国务院政策文件库历史归档 + 精确年份检索」"
                "确认尚未公布；不写占位数据。下次自动检查 %s。"
                % (year, next_check(today)), **base)
        entries = [hist_entry]
        source_note = "国务院政策文件库历史归档（最新政策索引已将其移除/不可用）"

    entry = entries[0]
    url = notice_url or str(entry.get("URL") or "")
    if notice_url and notice_url != str(entry.get("URL") or ""):
        return _status("source-conflict", year,
                       "人工指定的通知地址与官方来源记录的地址不一致，停止自动提交。", **base)
    published = str(entry.get("DOCRELPUBTIME") or "")
    if notice_bytes is None:
        if not allow_network:
            return _status("needs-human-review", year,
                           "已发现正式通知，但未提供通知全文离线样本；转人工确认。", **base)
        try:
            notice_bytes = fetch(url)
        except FetchError as exc:
            return _status("check-unavailable", year,
                           "已发现正式通知但全文抓取失败，不猜测数据：%s" % exc, **base)

    candidate, errors = parse_notice(notice_bytes, year, data, url=url, published=published)
    if errors:
        return _status("needs-human-review", year,
                       "官方通知无法可靠自动解析，不写任何数据：" + "；".join(errors),
                       errors=errors, **base)
    # 历史政策库条目的文号与通知全文文号必须一致，防止取到同名但不同文件。
    pcode = str(entry.get("PCODE") or "")
    if pcode and candidate.get("wenhao") and pcode != candidate["wenhao"]:
        return _status("needs-human-review", year,
                       "官方检索记录文号 %s 与通知全文文号 %s 不一致，停止自动提交。"
                       % (pcode, candidate["wenhao"]), **base)
    return _status("ready", year,
                   "%d 年官方通知解析并通过全部校验，可生成更新。" % year,
                   candidate=candidate, source=source_note, **base)


def apply_candidate(data: dict, candidate: dict) -> dict:
    """把已校验的候选写进 JSON 与 index.html 受保护区块。"""
    year = int(candidate["year"])
    if str(year) in data["schedules"]:
        return _status("already-present", year, "%d 年安排已存在。" % year)

    new_data = json.loads(json.dumps(data))  # 深拷贝，不改动内存里的旧数据
    new_data["schedules"][str(year)] = candidate["schedule"]
    new_data["sources"][str(year)] = {
        "title": candidate["title"],
        "wenhao": candidate.get("wenhao"),
        "url": candidate.get("url"),
        "published": candidate.get("published"),
    }
    errors = validate_data(new_data)
    if errors:
        raise UpdaterError("新数据整体校验失败：" + "；".join(errors))

    old_index = INDEX_PATH.read_text(encoding="utf-8")
    new_index = replace_block(old_index, render_block(new_data))
    new_json = json.dumps(new_data, ensure_ascii=False, indent=2) + "\n"

    old_json_bytes = DATA_PATH.read_bytes()
    old_index_bytes = INDEX_PATH.read_bytes()

    def _restore():
        _write_bytes(DATA_PATH, old_json_bytes)
        _write_bytes(INDEX_PATH, old_index_bytes)

    atomic_write_pairs([(DATA_PATH, new_json), (INDEX_PATH, new_index)])

    # 写后复核：旧年份一个字节都不能变，且 @media 头数量不变。
    reloaded = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    for old_year, old_schedule in data["schedules"].items():
        if reloaded["schedules"].get(old_year) != old_schedule:
            _restore()
            raise UpdaterError("旧年份数据被改动，已回滚")
    if media_count(INDEX_PATH.read_text(encoding="utf-8")) != media_count(old_index):
        _restore()
        raise UpdaterError("@media 头数量变化，已回滚")
    return _status("updated", year,
                   "%d 年放假安排已写入 %s 与 %s（旧年份与页面其它代码未改动）。"
                   % (year, DATA_PATH.name, INDEX_PATH.name))


def summary_md(result: dict) -> str:
    lines = [
        "### 中国法定节假日年度检查",
        "",
        "- 目标年份：`%s`" % result["target_year"],
        "- 结果：`%s`" % result["status"],
        "- 说明：%s" % result["message"],
    ]
    if result.get("next_check"):
        lines.append("- 下次自动检查：`%s`" % result["next_check"])
    if result.get("source"):
        lines.append("- 发现来源：`%s`" % result["source"])
    if result.get("candidate"):
        c = result["candidate"]
        lines += [
            "- 官方通知：%s" % c["title"],
            "- 文号：%s" % (c.get("wenhao") or "（通知未标注）"),
            "- 来源：%s" % (c.get("url") or "（离线样本）"),
            "- 调休上班日：%s" % "、".join(c["schedule"]["workdays"]),
        ]
    if result.get("errors"):
        lines.append("- 阻塞原因：")
        lines += ["  - %s" % e for e in result["errors"]]
    return "\n".join(lines) + "\n"


def _cli() -> int:
    ap = argparse.ArgumentParser(description="中国法定节假日年度更新器（stdlib-only）")
    ap.add_argument("command", choices=("check", "apply", "regenerate", "verify"))
    ap.add_argument("--root", default=str(ROOT), help="仓库根目录（测试可指向临时目录）")
    ap.add_argument("--today", default=None, help="覆盖当天日期 YYYY-MM-DD（CI/测试用）")
    ap.add_argument("--index-feed", default=None, help="最新政策索引离线样本文件")
    ap.add_argument("--history-feed", default=None, help="国务院政策文件库历史归档检索离线样本")
    ap.add_argument("--exact-feed", default=None, help="精确年份检索离线样本")
    ap.add_argument("--notice-html", default=None, help="通知全文离线样本文件")
    ap.add_argument("--notice-url", default=None, help="人工确认的官方通知地址")
    ap.add_argument("--no-network", action="store_true", help="禁止任何联网（CI 默认行为）")
    ap.add_argument("--dry-run", action="store_true", help="apply 只校验不写文件")
    ap.add_argument("--candidate-file", default=None,
                    help="apply 直接使用 check 阶段导出并校验过的候选 JSON（不再联网）")
    ap.add_argument("--json", action="store_true", help="输出机器可读 JSON")
    ap.add_argument("--status-file", default=None, help="写不含候选数据的状态 JSON（给 CI 读）")
    ap.add_argument("--candidate-out", default=None, help="ready 时把候选 JSON 写到该路径")
    ap.add_argument("--summary-file", default=None, help="写 Markdown 摘要到文件")
    args = ap.parse_args()

    global DATA_PATH, INDEX_PATH
    root = Path(args.root).resolve()
    DATA_PATH = root / "holidays" / "cn-holidays.json"
    INDEX_PATH = root / "src" / "index.html"

    today = dt.date.fromisoformat(args.today) if args.today else today_jst()
    try:
        data = load_data()
        if args.command == "verify":
            errors = validate_data(data)
            prefix, block, _ = split_index(INDEX_PATH.read_text(encoding="utf-8"))
            del prefix
            if block != render_block(data):
                errors.append("index.html 受保护区块与 holidays/cn-holidays.json 不一致")
            if media_count(INDEX_PATH.read_text(encoding="utf-8")) != 5:
                errors.append("index.html 的 @media 头数量不是 5")
            result = _status("error" if errors else "ok", target_year(today),
                             "；".join(errors) if errors else "数据与前端区块一致，@media 头完整。",
                             errors=errors)
        elif args.command == "regenerate":
            old = INDEX_PATH.read_text(encoding="utf-8")
            generated = render_block(data)
            _, current, _ = split_index(old)
            if current == generated:
                result = _status("ok", target_year(today), "前端区块已是最新，无需改写。")
            else:
                new = replace_block(old, generated)
                atomic_write_pairs([(INDEX_PATH, new)])
                result = _status("updated", target_year(today),
                                 "已按结构化数据重新生成前端受保护区块。")
        elif args.command == "apply" and args.candidate_file:
            # 用 check 阶段导出、人已确认过的候选；写入前再校验一次，不联网。
            candidate = json.loads(Path(args.candidate_file).read_text(encoding="utf-8"))
            if int(candidate["year"]) != target_year(today):
                raise UpdaterError("候选年份与本次目标年份不一致")
            extra = validate_schedule(int(candidate["year"]), candidate["schedule"], data)
            if extra:
                raise UpdaterError("候选数据复核失败：" + "；".join(extra))
            result = (_status("ready", target_year(today),
                              "dry-run：候选数据通过全部校验，未写文件。",
                              candidate=candidate) if args.dry_run
                      else apply_candidate(data, candidate))
        else:
            feed = Path(args.index_feed).read_bytes() if args.index_feed else None
            history = Path(args.history_feed).read_bytes() if args.history_feed else None
            exact = Path(args.exact_feed).read_bytes() if args.exact_feed else None
            notice = Path(args.notice_html).read_bytes() if args.notice_html else None
            result = run_check(data, today, feed_bytes=feed, notice_bytes=notice,
                               notice_url=args.notice_url,
                               allow_network=not args.no_network,
                               history_bytes=history, exact_bytes=exact)
            if args.command == "apply" and result["status"] == "ready":
                if args.dry_run:
                    result = _status("ready", result["target_year"],
                                     "dry-run：候选数据通过全部校验，未写文件。",
                                     candidate=result.get("candidate"))
                else:
                    result = apply_candidate(data, result["candidate"])
    except (UpdaterError, OSError, ValueError) as exc:
        result = _status("error", target_year(today), str(exc))

    if args.summary_file:
        Path(args.summary_file).write_text(summary_md(result), encoding="utf-8")
    if args.status_file:
        Path(args.status_file).write_text(
            json.dumps({k: v for k, v in result.items() if k != "candidate"},
                       ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if args.candidate_out and result.get("candidate"):
        Path(args.candidate_out).write_text(
            json.dumps(result["candidate"], ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
    if args.json:
        print(json.dumps({k: v for k, v in result.items() if k != "candidate"},
                         ensure_ascii=False, indent=2))
        if result.get("candidate"):
            print("--candidate-json--")
            print(json.dumps(result["candidate"], ensure_ascii=False))
    else:
        print(summary_md(result))
    if result["status"] in ("error", "check-unavailable"):
        return EXIT_CHECK_FAILED
    if result["status"] in ("needs-human-review", "untrusted-source", "source-conflict"):
        return EXIT_NEEDS_HUMAN
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(_cli())
