_replace = os.replace  # 测试可注入失败，验证回滚语义


def _write_bytes(path: Path, payload: bytes) -> None:
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        _replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def atomic_write_pairs(pairs) -> None:
    """pairs: [(Path, str)]。要么两个文件都更新，要么都回到写入前状态。"""
    originals = {path: path.read_bytes() for path, _ in pairs}
    staged = []
    replaced = []
    try:
        for path, content in pairs:
            fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp",
                                       dir=str(path.parent))
            with os.fdopen(fd, "wb") as fh:
                fh.write(content.encode("utf-8"))
                fh.flush()
                os.fsync(fh.fileno())
            staged.append((path, tmp))
        for path, tmp in staged:
            _replace(tmp, path)
            replaced.append(path)
        for path, content in pairs:
            if path.read_bytes() != content.encode("utf-8"):
                raise OSError("写入后校验不通过: %s" % path.name)
    except BaseException:
        failed_restore = []
        for path in replaced:
            try:
                _write_bytes(path, originals[path])
            except OSError:
                failed_restore.append(str(path))
        if failed_restore:
            raise UpdaterError("回滚不完整，需要人工恢复: %s" % ", ".join(failed_restore))
        raise
    finally:
        for _, tmp in staged:
            if os.path.exists(tmp):
                os.unlink(tmp)


